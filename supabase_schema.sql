-- Organizations: usuario ve apenas a propria organizacao.
drop policy if exists org_select on public.organizations;
create policy org_select on public.organizations
for select to authenticated
using (id = (select (public.current_profile()).organization_id));

-- Squads: tecnico/admin do squad ve apenas o seu; super_admin ve todos da organizacao.
drop policy if exists squads_select on public.squads;
create policy squads_select on public.squads
for select to authenticated
using (public.can_read_squad(id));

-- Profiles: usuario ve o proprio perfil; admins podem ver perfis dentro do escopo que administram.
drop policy if exists profiles_select on public.profiles;
create policy profiles_select on public.profiles
for select to authenticated
using (
  user_id = (select auth.uid())
  or (squad_id is not null and public.can_admin_squad(squad_id))
  or (public.is_super_admin() and organization_id = (select (public.current_profile()).organization_id))
);

-- A criação cotidiana de usuários é feita pela Edge Function create-user com service_role.
-- Estas policies mantêm uma barreira adicional; a Data API do navegador recebe apenas SELECT em profiles.
-- Edicao direta de profiles fica reservada ao admin geral por seguranca.
drop policy if exists profiles_insert on public.profiles;
create policy profiles_insert on public.profiles
for insert to authenticated
with check (public.is_super_admin());

drop policy if exists profiles_update on public.profiles;
create policy profiles_update on public.profiles
for update to authenticated
using (public.is_super_admin())
with check (public.is_super_admin());

